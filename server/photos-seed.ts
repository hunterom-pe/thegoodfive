/**
 * Build the starter photo library for review. Run by a person, once; read-only for the database.
 *
 *   npm run photos:seed
 *
 * Searches Unsplash with a fixed, hand-written list of subjects per story category, keeps the best few
 * photos of each, and writes (1) a SQL file that adds them to photo_library and (2) a preview with
 * thumbnails and credits. Nothing is inserted by this script: a person reads the preview, deletes any
 * photo they don't want from the SQL, and runs it in the Supabase SQL Editor after the photo_library migration.
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { rankPhotos, searchPhotos, toCandidate, type UnsplashPhoto } from './pipeline/unsplash.ts'
import { env } from './store.ts'

/** Subjects a good-news story in each category might plausibly be illustrated with. Mostly people-free. */
const SUBJECTS: Record<string, string[]> = {
  nature: ['forest river sunlight', 'coral reef ocean', 'wildflower meadow', 'mountain lake sunrise', 'wetland birds', 'green hills valley'],
  science: ['telescope night sky', 'laboratory microscope', 'earth from space', 'crystal light macro', 'research laboratory glassware', 'observatory stars'],
  health: ['hospital corridor', 'fresh vegetables market', 'running trail morning', 'microscope cells', 'medicine pills glass', 'yoga mat sunrise'],
  humanity: ['community garden', 'village street', 'neighbours helping', 'library books reading', 'hands together', 'food market stalls'],
  progress: ['wind turbines field', 'solar panels roof', 'railway bridge sunrise', 'city skyline morning', 'new school building', 'clean water tap'],
}
const PER_SUBJECT = 3
const PEOPLE = /\b(man|men|woman|women|person|people|portrait|boy|girl|child|children|kid|kids|baby|face|faces|selfie|smiling|couple|family|student|students|crowd|hands?|volunteers?|neighbou?rs|friends|team|doctor|nurse|runner)\b/i

const c = env()
if (!c.unsplashKey) throw new Error('Needs UNSPLASH_ACCESS_KEY in .env.local.')
const q = (s: string) => `'${s.replace(/'/g, "''")}'`
const words = (s: string) => [...new Set(s.toLowerCase().replace(/[^a-z0-9\s]/g, ' ').split(/\s+/).filter((w) => w.length > 3))]

const rows: string[] = []
const preview: string[] = ['# Starter photo library: preview', '', 'Prepared for review. **Nothing has been added to the database.** Each photo is credited to its photographer and Unsplash, hotlinked from the API URL, and shown as an illustrative photo. Delete any you dislike from the SQL file before running it.', '']
const seen = new Set<string>()
let count = 0
for (const [category, subjects] of Object.entries(SUBJECTS)) {
  preview.push(`## ${category}`, '')
  for (const subject of subjects) {
    let found: UnsplashPhoto[] = []
    try {
      found = rankPhotos(await searchPhotos(subject, c.unsplashKey, 12), subject, { aboutPerson: false, exclude: seen }).slice(0, PER_SUBJECT)
    } catch (e) {
      console.log(`"${subject}": ${e instanceof Error ? e.message : e}`)
    }
    for (const p of found) {
      seen.add(p.id)
      const cand = toCandidate(p, c.appName, subject)
      const people = PEOPLE.test(`${p.alt_description ?? ''} ${p.description ?? ''}`)
      const alt = (p.alt_description ?? `Illustrative photo: ${subject}`).replace(/^./, (m) => m.toUpperCase())
      const keywords = words(`${subject} ${p.alt_description ?? ''}`).slice(0, 12)
      rows.push(
        `  (${q(p.id)}, ${q(p.urls.raw)}, ${q(alt)}, ${q(p.user.name)}, ${q(p.user.links.html)}, ${q(p.links.html)}, ${cand.downloadLocation ? q(cand.downloadLocation) : 'null'}, array['${category}']::public.story_category[], array[${keywords.map(q).join(', ')}]::text[], true, ${people})`,
      )
      preview.push(`- **${subject}** · ${alt}${people ? ' · *shows people*' : ''} · ${p.user.name}`, '', `  ![${alt}](${p.urls.raw}&w=360&auto=format&fit=crop&q=70)`, '')
      count++
    }
  }
}
const sql = `-- Starter photo library (${count} photos). Generated by \`npm run photos:seed\` from a fixed list of subjects.
-- Run AFTER 20261116000000_photo_library.sql. Safe to run twice. Delete any row you don't want.
insert into public.photo_library (unsplash_id, url, alt, credit, credit_url, source_url, download_location, categories, keywords, generic, shows_people)
values
${rows.join(',\n')}
on conflict (unsplash_id) do nothing;
`
mkdirSync('proposals', { recursive: true })
mkdirSync('supabase/seeds', { recursive: true })
writeFileSync('supabase/seeds/photo_library_seed.sql', sql)
writeFileSync('proposals/library-seed-preview.md', preview.join('\n'))
console.log(`${count} photos → supabase/seeds/photo_library_seed.sql and proposals/library-seed-preview.md`)
